(function initGtvMainRuntimeBootstrapWiring(globalObj) {
    "use strict";

    function requireFunction(value, label) {
        if (typeof value !== "function") {
            throw new Error(`Missing required dependency: ${label}`);
        }
        return value;
    }

    function requireObject(value, label) {
        if (!value || typeof value !== "object") {
            throw new Error(`Missing required dependency: ${label}`);
        }
        return value;
    }

    function createService(deps = {}) {
        const safeDeps = (deps && typeof deps === "object") ? deps : {};
        const requireObjectDep = (depName) => requireObject(safeDeps[depName], depName);
        const requireObjectMethod = (target, targetName, methodName) => (
            requireFunction(target[methodName], `${targetName}.${methodName}`)
        );
        const requireDepMethod = (depName, methodName = "createService") => (
            requireObjectMethod(requireObjectDep(depName), depName, methodName)
        );
        const resolveOptionalGetter = (depName, fallbackFactory) => (
            (typeof safeDeps[depName] === "function")
                ? safeDeps[depName]
                : fallbackFactory
        );
        const pickDeps = (...depNames) => depNames.reduce((acc, depName) => {
            acc[depName] = safeDeps[depName];
            return acc;
        }, {});
        const setOptionalService = (setterName, service) => {
            if (typeof safeDeps[setterName] === "function") {
                safeDeps[setterName](service);
            }
        };

        const deferDynamic = (getter) => (typeof safeDeps.deferDynamicCall === "function"
            ? safeDeps.deferDynamicCall(getter)
            : () => undefined);
        const bindFacade = (getter, methodName) => (typeof safeDeps.bindFacadeMethod === "function"
            ? safeDeps.bindFacadeMethod(getter, methodName)
            : () => undefined);
        const buildMainAppBootstrapConfig = () => ({
            ...pickDeps(
                "assertRequiredServices",
                "loadPersistence",
                "localizeAutoGeneratedNamesForCurrentLanguage",
                "savePersistenceSafely",
                "loadCurrentMultiStateFromActiveSubgroup",
                "loadThemePreference",
                "applyTheme",
                "loadUiScalePreference",
                "applyUiScale",
                "applyTranslations",
                "applyVersionBranding"
            ),
            initUI: bindFacade(safeDeps.getMainUiInitServiceRef, "initUI"),
            ...pickDeps("bindFloatingTooltipEvents"),
            initSearchAndSelect: bindFacade(safeDeps.getTimezoneSearchServiceRef, "initSearchAndSelect"),
            ...pickDeps("initCalculators"),
            startRealtimeTicker: bindFacade(safeDeps.getTimerEngineServiceRef, "startRealtimeTicker"),
            ...pickDeps("switchMainTab", "getPatchedMainTabState"),
            getCurrentMainTab: safeDeps.getPatchedMainTabState,
            updateClocks: deferDynamic(safeDeps.getUpdateClocksRef),
            ...pickDeps("showFatalError")
        });

        const serviceInvokeUtils = globalObj?.GTVServiceInvokeUtils || globalThis.GTVServiceInvokeUtils;
        if (!serviceInvokeUtils || typeof serviceInvokeUtils.createRequiredModuleService !== "function") {
            throw new Error("Missing required module API: GTVServiceInvokeUtils.createRequiredModuleService");
        }
        // Accessor proxy services are created directly (formerly one *-bindings module each) and
        // exposed as frozen copies, as the bindings did. The proxies module key is not forwarded.
        const ACCESSOR_SPECS = Object.freeze({
            UiBridge: {
                moduleKey: "runtimeUiBridgeAccessorProxiesModule",
                moduleName: "GTVMainRuntimeUiBridgeAccessorProxies",
                invalidMessage: "Invalid main runtime UI bridge accessor proxies service",
                requiredMethods: ["showFatalError","showToast","switchMainTab","refreshOptionToggleDividers","getCopyFieldLabel","getTimePartLabel","getDisplayColumns","getDisplayTimeInputMode","buildRowActionCells","renderList","renderTimelineFrame","resolveFixedTimeSlotUtcDate","getFixedTimeSlotHeaderLabel","renderFixedTimeTab"]
            },
            Operation: {
                moduleKey: "runtimeOperationAccessorProxiesModule",
                moduleName: "GTVMainRuntimeOperationAccessorProxies",
                invalidMessage: "Invalid main runtime operation accessor proxies service",
                requiredMethods: ["updateClocks","resolveLocalDatePartsByTimezoneAtDate","resolveLocalDatePartsByTimezone","buildStrictUtcDateFromParts","handleTimeChange","handleMultiRangeTimeChange","formatTimeTextByParts","formatSnapshotText","initCalculators","copyText","getPersistenceSnapshot","sanitizeGroup","loadPersistence"]
            },
            Bootstrap: {
                moduleKey: "runtimeBootstrapAccessorProxiesModule",
                moduleName: "GTVMainRuntimeBootstrapAccessorProxies",
                invalidMessage: "Invalid main runtime bootstrap accessor proxies service",
                requiredMethods: ["initApp","startBootstrapOnDomReady"]
            }
        });
        function createProxyAccessorService(kind, accessorDeps = {}) {
            const spec = ACCESSOR_SPECS[kind];
            const { [spec.moduleKey]: proxiesModule, ...forwardDeps } = accessorDeps;
            return Object.freeze({
                ...serviceInvokeUtils.createRequiredModuleService(
                    proxiesModule,
                    spec.moduleName,
                    forwardDeps,
                    spec.requiredMethods,
                    spec.invalidMessage
                )
            });
        }
        const createRuntimePublicApiService = requireDepMethod("runtimePublicApiBindings");
        const createMainAppBootstrapService = requireDepMethod(
            "mainCoreServices",
            "createMainAppBootstrapService"
        );

        const mainRuntimeUiBridgeAccessorService = createProxyAccessorService("UiBridge", pickDeps(
            "runtimeUiBridgeAccessorProxiesModule",
            "callServiceMethod",
            "getAppFeedbackService",
            "getTabOrchestratorService",
            "getFormatControlsService",
            "getTableRenderService",
            "getMainTimezoneTableFacadeService",
            "getMainTimelineFacadeService",
            "getMainFixedTimeFacadeService",
            "getMainFixedTimeTabFacadeService",
            "getPatchedSlotCountState",
            "getGlobalTimeState",
            "serviceMethodMissingToken",
            "consoleError"
        ));

        const mainRuntimeOperationAccessorService = createProxyAccessorService("Operation", pickDeps(
            "runtimeOperationAccessorProxiesModule",
            "callServiceMethod",
            "getMainOrchestrationFlowServices",
            "getTimeInputMutationsService",
            "getSnapshotFormatService",
            "getCalculatorActionsService",
            "getGroupStateService",
            "getPersistenceService",
            "defaultCopyTimePartsEnabled"
        ));

        let mainRuntimeBootstrapAccessorService = null;
        const getMainRuntimeBootstrapAccessorService = resolveOptionalGetter(
            "getMainRuntimeBootstrapAccessorService",
            () => mainRuntimeBootstrapAccessorService
        );
        const mainRuntimePublicApiService = createRuntimePublicApiService({
            getUiBridgeAccessorService: () => mainRuntimeUiBridgeAccessorService,
            getOperationAccessorService: () => mainRuntimeOperationAccessorService,
            getBootstrapAccessorService: () => getMainRuntimeBootstrapAccessorService(),
            ...pickDeps("getGlobalTimeState", "defaultCopyTimePartsEnabled")
        });

        const mainAppBootstrapConfig = buildMainAppBootstrapConfig();
        const mainAppBootstrapService = createMainAppBootstrapService(mainAppBootstrapConfig);
        setOptionalService("setMainAppBootstrapService", mainAppBootstrapService);

        mainRuntimeBootstrapAccessorService = createProxyAccessorService("Bootstrap", {
            ...pickDeps("runtimeBootstrapAccessorProxiesModule", "getDocumentRefOrNull"),
            getMainAppBootstrapService: resolveOptionalGetter(
                "getMainAppBootstrapService",
                () => mainAppBootstrapService
            )
        });
        setOptionalService("setMainRuntimeBootstrapAccessorService", mainRuntimeBootstrapAccessorService);

        return Object.freeze({
            mainRuntimeUiBridgeAccessorService,
            mainRuntimeOperationAccessorService,
            mainRuntimePublicApiService,
            mainAppBootstrapService,
            mainRuntimeBootstrapAccessorService
        });
    }

    globalObj.GTVMainRuntimeBootstrapWiring = Object.freeze({
        createService
    });
})(typeof window !== "undefined" ? window : globalThis);
