(function initGtvMainGroupLocalizationServices(globalObj) {
    "use strict";

    function createService(deps = {}) {
        const safeDeps = (deps && typeof deps === "object") ? deps : {};
        const serviceInvokeUtils = (
            safeDeps.GTV_SERVICE_INVOKE_UTILS
            && typeof safeDeps.GTV_SERVICE_INVOKE_UTILS === "object"
        )
            ? safeDeps.GTV_SERVICE_INVOKE_UTILS
            : (
                globalObj.GTVServiceInvokeUtils
                && typeof globalObj.GTVServiceInvokeUtils === "object"
            )
                ? globalObj.GTVServiceInvokeUtils
                : null;
        const getGroups = (typeof safeDeps.getGroups === "function")
            ? safeDeps.getGroups
            : (() => (Array.isArray(safeDeps.groups) ? safeDeps.groups : []));
        const getCurrentGroup = (typeof safeDeps.getCurrentGroup === "function")
            ? safeDeps.getCurrentGroup
            : (() => null);
        const getMultiStateService = (typeof safeDeps.getMultiStateService === "function")
            ? safeDeps.getMultiStateService
            : (() => null);
        const t = (typeof safeDeps.t === "function")
            ? safeDeps.t
            : ((key) => String(key || ""));
        const getMultiRangeState = (typeof safeDeps.getMultiRangeState === "function")
            ? safeDeps.getMultiRangeState
            : (() => ({
                multiRangeCount: 1,
                multiRanges: [],
                multiRangeCollapsed: [],
                multiRangeStartEditEnabled: [],
                multiRangeEndEditEnabled: []
            }));
        const setMultiRangeState = (typeof safeDeps.setMultiRangeState === "function")
            ? safeDeps.setMultiRangeState
            : (() => { });
        const sanitizeMultiRangeCount = (typeof safeDeps.sanitizeMultiRangeCount === "function")
            ? safeDeps.sanitizeMultiRangeCount
            : ((value) => {
                const parsed = Number(value);
                if (!Number.isFinite(parsed)) return 1;
                return Math.max(1, Math.trunc(parsed));
            });
        const sanitizeMultiRangeTitle = (typeof safeDeps.sanitizeMultiRangeTitle === "function")
            ? safeDeps.sanitizeMultiRangeTitle
            : ((value) => String(value || "").trim());
        const sanitizeUtcMs = (typeof safeDeps.sanitizeUtcMs === "function")
            ? safeDeps.sanitizeUtcMs
            : ((value, fallbackMs) => {
                const parsed = Number(value);
                return Number.isFinite(parsed) ? parsed : fallbackMs;
            });
        const ensureMultiRangeState = (typeof safeDeps.ensureMultiRangeState === "function")
            ? safeDeps.ensureMultiRangeState
            : (() => { });
        const refreshMultiRangeControls = (typeof safeDeps.refreshMultiRangeControls === "function")
            ? safeDeps.refreshMultiRangeControls
            : (() => { });
        const now = (typeof safeDeps.now === "function")
            ? safeDeps.now
            : (() => Date.now());

        const DEFAULT_GROUP_BASE_CANDIDATES = ["Default Group", "\uAE30\uBCF8 \uADF8\uB8F9"];
        const DEFAULT_SUBGROUP_BASE_CANDIDATES = [
            "Subgroup",
            "Aux Group",
            "\uC11C\uBE0C \uADF8\uB8F9",
            "\uBCF4\uC870 \uADF8\uB8F9"
        ];

        function resolveMultiStateService() {
            if (serviceInvokeUtils && typeof serviceInvokeUtils.resolveService === "function") {
                return serviceInvokeUtils.resolveService(getMultiStateService);
            }
            const service = getMultiStateService();
            return (service && typeof service === "object") ? service : null;
        }

        function invokeMultiStateService(methodName, args = [], fallback = undefined) {
            if (serviceInvokeUtils && typeof serviceInvokeUtils.invokeGetterMethod === "function") {
                return serviceInvokeUtils.invokeGetterMethod(getMultiStateService, methodName, args, fallback);
            }
            const multiStateService = resolveMultiStateService();
            if (!multiStateService || typeof multiStateService[methodName] !== "function") {
                return fallback;
            }
            return multiStateService[methodName](...args);
        }

        function parseAutoGeneratedIndexedName(name, baseCandidates = []) {
            const text = (typeof name === "string") ? name.trim() : "";
            if (!text) return { matched: false, number: null };

            for (const base of baseCandidates) {
                const safeBase = String(base || "").trim();
                if (!safeBase) continue;
                if (text === safeBase) {
                    return { matched: true, number: null };
                }
                const escapedBase = safeBase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
                const matched = text.match(new RegExp(`^${escapedBase}\\s+(\\d+)$`));
                if (matched) {
                    return { matched: true, number: parseInt(matched[1], 10) };
                }
            }
            return { matched: false, number: null };
        }

        function localizeAutoGeneratedNamesForCurrentLanguage() {
            const groups = getGroups();
            if (!Array.isArray(groups) || !groups.length) return false;
            let changed = false;

            const nextGroupBase = t("default_group_name");
            const nextSubgroupBase = t("default_subgroup_name");
            groups.forEach((group) => {
                if (!group || typeof group !== "object") return;
                const parsedGroup = parseAutoGeneratedIndexedName(group.name, DEFAULT_GROUP_BASE_CANDIDATES);
                if (parsedGroup.matched) {
                    const nextGroupName = Number.isFinite(parsedGroup.number)
                        ? `${nextGroupBase} ${parsedGroup.number}`
                        : nextGroupBase;
                    if (group.name !== nextGroupName) {
                        group.name = nextGroupName;
                        changed = true;
                    }
                }

                if (invokeMultiStateService("ensureGroupMultiSubgroups", [group], false) === false) return;
                const subgroups = Array.isArray(group.multiSubgroups) ? group.multiSubgroups : [];
                subgroups.forEach((subgroup, subgroupIdx) => {
                    const parsedSubgroup = parseAutoGeneratedIndexedName(
                        subgroup?.name,
                        DEFAULT_SUBGROUP_BASE_CANDIDATES
                    );
                    if (!parsedSubgroup.matched) return;
                    const nextSubgroupName = Number.isFinite(parsedSubgroup.number)
                        ? `${nextSubgroupBase} ${parsedSubgroup.number}`
                        : `${nextSubgroupBase} ${subgroupIdx + 1}`;
                    if (subgroup.name !== nextSubgroupName) {
                        subgroup.name = nextSubgroupName;
                        changed = true;
                    }
                });
            });

            return changed;
        }

        function getCurrentMultiSubgroup() {
            const group = getCurrentGroup();
            if (!group) return null;
            invokeMultiStateService("ensureGroupMultiSubgroups", [group]);
            const subgroups = Array.isArray(group.multiSubgroups) ? group.multiSubgroups : [];
            return subgroups.find((subgroup) => subgroup.id === group.activeMultiSubgroupId) || subgroups[0] || null;
        }

        function getCurrentMultiSubgroupName() {
            const subgroup = getCurrentMultiSubgroup();
            const fallback = invokeMultiStateService("getDefaultMultiSubgroupName", [0], "subgroup");
            const fallbackName = String(fallback || "").trim() || "subgroup";
            const sanitizedName = invokeMultiStateService(
                "sanitizeMultiSubgroupName",
                [subgroup?.name, fallbackName],
                null
            );
            if (typeof sanitizedName === "string") {
                return sanitizedName.trim() || fallbackName;
            }
            return String(subgroup?.name || "").trim() || fallbackName;
        }

        function syncCurrentMultiStateToActiveSubgroup() {
            const group = getCurrentGroup();
            if (!group) return;

            if (invokeMultiStateService("ensureGroupMultiSubgroups", [group], false) === false) return;
            ensureMultiRangeState();

            const subgroup = getCurrentMultiSubgroup();
            if (!subgroup) return;

            const fallbackName = invokeMultiStateService("getDefaultMultiSubgroupName", [0], "subgroup");
            const sanitizedName = invokeMultiStateService("sanitizeMultiSubgroupName", [subgroup.name, fallbackName], null);
            if (sanitizedName === null) {
                subgroup.name = String(subgroup.name || "").trim() || fallbackName;
            } else {
                subgroup.name = sanitizedName;
            }

            const state = getMultiRangeState() || {};
            const safeRanges = Array.isArray(state.multiRanges) ? state.multiRanges : [];
            subgroup.multiRangeCount = sanitizeMultiRangeCount(state.multiRangeCount);
            subgroup.multiRanges = safeRanges.map((range) => ({
                startUtcMs: sanitizeUtcMs(range?.startUtcMs, now()),
                endUtcMs: sanitizeUtcMs(range?.endUtcMs, now())
            }));
            subgroup.multiRangeCollapsed = (Array.isArray(state.multiRangeCollapsed) ? state.multiRangeCollapsed : [])
                .map((flag) => !!flag);
            subgroup.multiRangeStartEditEnabled = (Array.isArray(state.multiRangeStartEditEnabled) ? state.multiRangeStartEditEnabled : [])
                .map((flag) => !!flag);
            subgroup.multiRangeEndEditEnabled = (Array.isArray(state.multiRangeEndEditEnabled) ? state.multiRangeEndEditEnabled : [])
                .map((flag) => !!flag);
        }

        function loadCurrentMultiStateFromActiveSubgroup() {
            const subgroup = getCurrentMultiSubgroup();
            const normalized = invokeMultiStateService("sanitizeMultiStatePayload", [subgroup, null], null);
            if (!normalized || typeof normalized !== "object") return;

            setMultiRangeState({
                multiRangeCount: normalized.multiRangeCount,
                multiRanges: normalized.multiRanges,
                multiRangeCollapsed: normalized.multiRangeCollapsed,
                multiRangeStartEditEnabled: normalized.multiRangeStartEditEnabled,
                multiRangeEndEditEnabled: normalized.multiRangeEndEditEnabled,
                multiRangeTitle: sanitizeMultiRangeTitle(getCurrentMultiSubgroupName())
            });

            ensureMultiRangeState();
            refreshMultiRangeControls();
        }

        return Object.freeze({
            parseAutoGeneratedIndexedName,
            localizeAutoGeneratedNamesForCurrentLanguage,
            getCurrentMultiSubgroup,
            getCurrentMultiSubgroupName,
            syncCurrentMultiStateToActiveSubgroup,
            loadCurrentMultiStateFromActiveSubgroup
        });
    }

    globalObj.GTVMainGroupLocalizationServices = Object.freeze({
        createService
    });
})(typeof window !== "undefined" ? window : globalThis);
