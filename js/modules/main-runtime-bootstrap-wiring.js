(function initGtvMainRuntimeBootstrapWiring(globalObj) {
    "use strict";

    function requireFunction(value, label) {
        if (typeof value !== "function") {
            throw new Error(`Missing required dependency: ${label}`);
        }
        return value;
    }

    function requireObject(value, label) {
        if (!value || typeof value !== "object") {
            throw new Error(`Missing required dependency: ${label}`);
        }
        return value;
    }

    function createService(deps = {}) {
        const safeDeps = (deps && typeof deps === "object") ? deps : {};
        const requireObjectDep = (depName) => requireObject(safeDeps[depName], depName);
        const requireObjectMethod = (target, targetName, methodName) => (
            requireFunction(target[methodName], `${targetName}.${methodName}`)
        );
        const requireDepMethod = (depName, methodName = "createService") => (
            requireObjectMethod(requireObjectDep(depName), depName, methodName)
        );
        const resolveOptionalGetter = (depName, fallbackFactory) => (
            (typeof safeDeps[depName] === "function")
                ? safeDeps[depName]
                : fallbackFactory
        );
        const pickDeps = (...depNames) => depNames.reduce((acc, depName) => {
            acc[depName] = safeDeps[depName];
            return acc;
        }, {});
        const setOptionalService = (setterName, service) => {
            if (typeof safeDeps[setterName] === "function") {
                safeDeps[setterName](service);
            }
        };

        const createRuntimeUiBridgeAccessorService = requireDepMethod("runtimeUiBridgeAccessorBindings");
        const createRuntimeOperationAccessorService = requireDepMethod("runtimeOperationAccessorBindings");
        const createRuntimePublicApiService = requireDepMethod("runtimePublicApiBindings");
        const createRuntimeBootstrapAccessorService = requireDepMethod("runtimeBootstrapAccessorBindings");
        const buildMainAppBootstrapConfig = requireDepMethod(
            "mainRuntimeServiceConfigBuilderService",
            "buildMainAppBootstrapConfig"
        );
        const createMainAppBootstrapService = requireDepMethod(
            "mainCoreServices",
            "createMainAppBootstrapService"
        );

        const mainRuntimeUiBridgeAccessorService = createRuntimeUiBridgeAccessorService(pickDeps(
            "runtimeUiBridgeAccessorProxiesModule",
            "callServiceMethod",
            "getAppFeedbackService",
            "getTabOrchestratorService",
            "getFormatControlsService",
            "getTableRenderService",
            "getMainTimezoneTableFacadeService",
            "getMainTimelineFacadeService",
            "getMainFixedTimeFacadeService",
            "getMainFixedTimeTabFacadeService",
            "getPatchedSlotCountState",
            "getGlobalTimeState",
            "serviceMethodMissingToken",
            "consoleError"
        ));

        const mainRuntimeOperationAccessorService = createRuntimeOperationAccessorService(pickDeps(
            "runtimeOperationAccessorProxiesModule",
            "callServiceMethod",
            "getMainOrchestrationFlowServices",
            "getTimeInputMutationsService",
            "getSnapshotFormatService",
            "getCalculatorActionsService",
            "getGroupStateService",
            "getPersistenceService",
            "defaultCopyTimePartsEnabled"
        ));

        let mainRuntimeBootstrapAccessorService = null;
        const getMainRuntimeBootstrapAccessorService = resolveOptionalGetter(
            "getMainRuntimeBootstrapAccessorService",
            () => mainRuntimeBootstrapAccessorService
        );
        const mainRuntimePublicApiService = createRuntimePublicApiService({
            getUiBridgeAccessorService: () => mainRuntimeUiBridgeAccessorService,
            getOperationAccessorService: () => mainRuntimeOperationAccessorService,
            getBootstrapAccessorService: () => getMainRuntimeBootstrapAccessorService(),
            ...pickDeps("getGlobalTimeState", "defaultCopyTimePartsEnabled")
        });

        const mainAppBootstrapConfig = buildMainAppBootstrapConfig(pickDeps(
            "assertRequiredServices",
            "loadPersistence",
            "localizeAutoGeneratedNamesForCurrentLanguage",
            "savePersistenceSafely",
            "loadCurrentMultiStateFromActiveSubgroup",
            "loadThemePreference",
            "applyTheme",
            "loadUiScalePreference",
            "applyUiScale",
            "applyTranslations",
            "applyVersionBranding",
            "bindFacadeMethod",
            "getMainUiInitServiceRef",
            "bindFloatingTooltipEvents",
            "initDragAndDrop",
            "getTimezoneSearchServiceRef",
            "initCalculators",
            "getTimerEngineServiceRef",
            "switchMainTab",
            "getPatchedMainTabState",
            "deferDynamicCall",
            "getUpdateClocksRef",
            "showFatalError"
        ));
        const mainAppBootstrapService = createMainAppBootstrapService(mainAppBootstrapConfig);
        setOptionalService("setMainAppBootstrapService", mainAppBootstrapService);

        mainRuntimeBootstrapAccessorService = createRuntimeBootstrapAccessorService({
            ...pickDeps("runtimeBootstrapAccessorProxiesModule", "getDocumentRefOrNull"),
            getMainAppBootstrapService: resolveOptionalGetter(
                "getMainAppBootstrapService",
                () => mainAppBootstrapService
            )
        });
        setOptionalService("setMainRuntimeBootstrapAccessorService", mainRuntimeBootstrapAccessorService);

        return Object.freeze({
            mainRuntimeUiBridgeAccessorService,
            mainRuntimeOperationAccessorService,
            mainRuntimePublicApiService,
            mainAppBootstrapService,
            mainRuntimeBootstrapAccessorService
        });
    }

    globalObj.GTVMainRuntimeBootstrapWiring = Object.freeze({
        createService
    });
})(typeof window !== "undefined" ? window : globalThis);
