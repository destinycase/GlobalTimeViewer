(function initGtvMainAppBootstrap(globalObj) {
    "use strict";

    function createService(deps = {}) {
        const safeDeps = (deps && typeof deps === "object") ? deps : {};
        const getWindowRef = (typeof safeDeps.getWindowRef === "function")
            ? safeDeps.getWindowRef
            : (() => {
                if (safeDeps.windowRef && typeof safeDeps.windowRef === "object") return safeDeps.windowRef;
                if (safeDeps.window && typeof safeDeps.window === "object") return safeDeps.window;
                if (globalObj?.window && typeof globalObj.window === "object") return globalObj.window;
                if (typeof window === "object" && window) return window;
                if (globalObj && typeof globalObj === "object") return globalObj;
                return null;
            });
        const getDocumentRef = (typeof safeDeps.getDocumentRef === "function")
            ? safeDeps.getDocumentRef
            : (() => {
                if (safeDeps.documentRef && typeof safeDeps.documentRef.getElementById === "function") return safeDeps.documentRef;
                if (safeDeps.document && typeof safeDeps.document.getElementById === "function") return safeDeps.document;
                const windowRef = getWindowRef();
                if (windowRef?.document && typeof windowRef.document.getElementById === "function") return windowRef.document;
                if (globalObj?.document && typeof globalObj.document.getElementById === "function") return globalObj.document;
                if (typeof document !== "undefined" && document && typeof document.getElementById === "function") return document;
                return null;
            });
        const bootstrapStepTimeoutMs = Number.isFinite(Number(safeDeps.bootstrapStepTimeoutMs))
            ? Math.max(1000, Math.trunc(Number(safeDeps.bootstrapStepTimeoutMs)))
            : 10000;
        const setTimeoutFn = (typeof safeDeps.setTimeoutFn === "function")
            ? safeDeps.setTimeoutFn
            : ((fn, ms) => {
                const windowRef = getWindowRef();
                if (windowRef && typeof windowRef.setTimeout === "function") {
                    return windowRef.setTimeout(fn, ms);
                }
                if (typeof globalObj?.setTimeout === "function") {
                    return globalObj.setTimeout(fn, ms);
                }
                if (typeof setTimeout === "function") {
                    return setTimeout(fn, ms);
                }
                if (typeof queueMicrotask === "function" && typeof fn === "function") {
                    queueMicrotask(fn);
                    return 0;
                }
                if (typeof Promise === "function" && typeof fn === "function") {
                    Promise.resolve().then(fn);
                    return 0;
                }
                if (typeof fn === "function") {
                    fn();
                }
                return 0;
            });
        const clearTimeoutFn = (typeof safeDeps.clearTimeoutFn === "function")
            ? safeDeps.clearTimeoutFn
            : ((id) => {
                const windowRef = getWindowRef();
                if (windowRef && typeof windowRef.clearTimeout === "function") {
                    windowRef.clearTimeout(id);
                    return;
                }
                if (typeof globalObj?.clearTimeout === "function") {
                    globalObj.clearTimeout(id);
                    return;
                }
                if (typeof clearTimeout === "function") {
                    clearTimeout(id);
                }
            });
        const assertRequiredServices = (typeof safeDeps.assertRequiredServices === "function")
            ? safeDeps.assertRequiredServices
            : (() => {});
        const loadPersistence = (typeof safeDeps.loadPersistence === "function")
            ? safeDeps.loadPersistence
            : (async () => {});
        const localizeAutoGeneratedNamesForCurrentLanguage = (typeof safeDeps.localizeAutoGeneratedNamesForCurrentLanguage === "function")
            ? safeDeps.localizeAutoGeneratedNamesForCurrentLanguage
            : (() => false);
        const savePersistenceSafely = (typeof safeDeps.savePersistenceSafely === "function")
            ? safeDeps.savePersistenceSafely
            : (async () => {});
        const loadCurrentMultiStateFromActiveSubgroup = (typeof safeDeps.loadCurrentMultiStateFromActiveSubgroup === "function")
            ? safeDeps.loadCurrentMultiStateFromActiveSubgroup
            : (() => {});
        const loadThemePreference = (typeof safeDeps.loadThemePreference === "function")
            ? safeDeps.loadThemePreference
            : (async () => null);
        const applyTheme = (typeof safeDeps.applyTheme === "function")
            ? safeDeps.applyTheme
            : (async () => {});
        const loadUiScalePreference = (typeof safeDeps.loadUiScalePreference === "function")
            ? safeDeps.loadUiScalePreference
            : (async () => null);
        const applyUiScale = (typeof safeDeps.applyUiScale === "function")
            ? safeDeps.applyUiScale
            : (async () => {});
        const applyTranslations = (typeof safeDeps.applyTranslations === "function")
            ? safeDeps.applyTranslations
            : (() => {});
        const applyVersionBranding = (typeof safeDeps.applyVersionBranding === "function")
            ? safeDeps.applyVersionBranding
            : (() => {});
        const initUI = (typeof safeDeps.initUI === "function")
            ? safeDeps.initUI
            : (() => {});
        const bindFloatingTooltipEvents = (typeof safeDeps.bindFloatingTooltipEvents === "function")
            ? safeDeps.bindFloatingTooltipEvents
            : (() => {});
        const initDragAndDrop = (typeof safeDeps.initDragAndDrop === "function")
            ? safeDeps.initDragAndDrop
            : (() => {});
        const initSearchAndSelect = (typeof safeDeps.initSearchAndSelect === "function")
            ? safeDeps.initSearchAndSelect
            : (() => {});
        const initCalculators = (typeof safeDeps.initCalculators === "function")
            ? safeDeps.initCalculators
            : (() => {});
        const startRealtimeTicker = (typeof safeDeps.startRealtimeTicker === "function")
            ? safeDeps.startRealtimeTicker
            : (() => {});
        const switchMainTab = (typeof safeDeps.switchMainTab === "function")
            ? safeDeps.switchMainTab
            : (() => {});
        const getCurrentMainTab = (typeof safeDeps.getCurrentMainTab === "function")
            ? safeDeps.getCurrentMainTab
            : (() => "live");
        const updateClocks = (typeof safeDeps.updateClocks === "function")
            ? safeDeps.updateClocks
            : (() => {});
        const showFatalError = (typeof safeDeps.showFatalError === "function")
            ? safeDeps.showFatalError
            : (() => {});

        function createBootstrapTimeoutError(stepName, timeoutMs) {
            const safeStepName = String(stepName || "unknown_step");
            const safeTimeoutMs = Number.isFinite(Number(timeoutMs))
                ? Math.max(1, Math.trunc(Number(timeoutMs)))
                : bootstrapStepTimeoutMs;
            const error = new Error(`[GTV] Bootstrap step timed out: ${safeStepName} (${safeTimeoutMs}ms)`);
            error.code = "BOOTSTRAP_TIMEOUT";
            error.step = safeStepName;
            error.timeoutMs = safeTimeoutMs;
            return error;
        }

        async function withBootstrapStepTimeout(stepName, runner) {
            const safeRunner = (typeof runner === "function")
                ? runner
                : (() => undefined);
            const taskResult = safeRunner();
            const isThenable = !!(taskResult && typeof taskResult.then === "function");
            if (!isThenable) return taskResult;
            let timerId = null;
            try {
                return await Promise.race([
                    taskResult,
                    new Promise((_, reject) => {
                        timerId = setTimeoutFn(() => {
                            reject(createBootstrapTimeoutError(stepName, bootstrapStepTimeoutMs));
                        }, bootstrapStepTimeoutMs);
                    })
                ]);
            } finally {
                if (timerId !== null && timerId !== undefined) {
                    clearTimeoutFn(timerId);
                }
            }
        }

        const removeLoadingOverlay = (typeof safeDeps.removeLoadingOverlay === "function")
            ? safeDeps.removeLoadingOverlay
            : (() => {
                try {
                    const documentRef = getDocumentRef();
                    const overlay = documentRef?.getElementById?.("app-loading-overlay") || null;
                    if (!overlay) return;
                    overlay.classList?.add?.("hidden");
                    if (typeof overlay.addEventListener === "function") {
                        overlay.addEventListener("transitionend", () => overlay.remove?.(), { once: true });
                    }
                    setTimeoutFn(() => {
                        if (overlay.parentNode && typeof overlay.remove === "function") {
                            overlay.remove();
                        }
                    }, 600);
                } catch (_e) {}
            });

        async function initApp() {
            try {
                assertRequiredServices();
                await withBootstrapStepTimeout("loadPersistence", () => loadPersistence());
                if (localizeAutoGeneratedNamesForCurrentLanguage()) {
                    await withBootstrapStepTimeout("savePersistenceSafely", () => savePersistenceSafely());
                }
                loadCurrentMultiStateFromActiveSubgroup();
                const themePreference = await withBootstrapStepTimeout("loadThemePreference", () => loadThemePreference());
                await withBootstrapStepTimeout("applyTheme", () => applyTheme(themePreference, false));
                const uiScalePreference = await withBootstrapStepTimeout("loadUiScalePreference", () => loadUiScalePreference());
                await withBootstrapStepTimeout("applyUiScale", () => applyUiScale(uiScalePreference, false));
                applyTranslations();
                applyVersionBranding();
                initUI();
                bindFloatingTooltipEvents();
                initDragAndDrop();
                initSearchAndSelect();
                initCalculators();
                startRealtimeTicker();
                switchMainTab(getCurrentMainTab());
                updateClocks();
                removeLoadingOverlay();
            } catch (err) {
                removeLoadingOverlay();
                showFatalError(err);
            }
        }

        return Object.freeze({
            initApp
        });
    }

    globalObj.GTVMainAppBootstrap = Object.freeze({
        createService
    });
})(typeof window !== "undefined" ? window : globalThis);
