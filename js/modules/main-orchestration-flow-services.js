(function initGtvMainOrchestrationFlowServices(globalObj) {
    "use strict";

    function createService(deps = {}) {
        const safeDeps = (deps && typeof deps === "object") ? deps : {};
        const getMainClockOrchestratorService = (typeof safeDeps.getMainClockOrchestratorService === "function")
            ? safeDeps.getMainClockOrchestratorService
            : (() => null);
        const getMainPersistenceSnapshotService = (typeof safeDeps.getMainPersistenceSnapshotService === "function")
            ? safeDeps.getMainPersistenceSnapshotService
            : (() => null);
        const getMainGroupLocalizationService = (typeof safeDeps.getMainGroupLocalizationService === "function")
            ? safeDeps.getMainGroupLocalizationService
            : (() => null);

        const warnedMissingMethods = new Set();
        const warnMissingServiceMethod = (typeof safeDeps.warnMissingServiceMethod === "function")
            ? safeDeps.warnMissingServiceMethod
            : ((serviceName, methodName) => {
                const key = `${serviceName}.${methodName}`;
                if (warnedMissingMethods.has(key)) return;
                warnedMissingMethods.add(key);
                console.warn(`[GTV] ${key} is unavailable. Fallback path will be used.`);
            });

        function getServiceMethod(serviceName, serviceRef, methodName) {
            if (serviceRef && typeof serviceRef[methodName] === "function") {
                return serviceRef[methodName].bind(serviceRef);
            }
            warnMissingServiceMethod(serviceName, methodName);
            return null;
        }

        function callServiceMethod(serviceName, serviceRef, methodName, args = [], fallbackValue) {
            const method = getServiceMethod(serviceName, serviceRef, methodName);
            if (!method) return fallbackValue;
            return method(...args);
        }

        function updateClocks() {
            return callServiceMethod(
                "mainClockOrchestratorService",
                getMainClockOrchestratorService(),
                "updateClocks",
                [],
                undefined
            );
        }

        function getPersistenceSnapshot() {
            return callServiceMethod(
                "mainPersistenceSnapshotService",
                getMainPersistenceSnapshotService(),
                "getPersistenceSnapshot",
                [],
                {}
            );
        }

        function parseAutoGeneratedIndexedName(name, baseCandidates = []) {
            return callServiceMethod(
                "mainGroupLocalizationServices",
                getMainGroupLocalizationService(),
                "parseAutoGeneratedIndexedName",
                [name, baseCandidates],
                { matched: false, number: null }
            );
        }

        function localizeAutoGeneratedNamesForCurrentLanguage() {
            return !!callServiceMethod(
                "mainGroupLocalizationServices",
                getMainGroupLocalizationService(),
                "localizeAutoGeneratedNamesForCurrentLanguage",
                [],
                false
            );
        }

        function getCurrentMultiSubgroup() {
            return callServiceMethod(
                "mainGroupLocalizationServices",
                getMainGroupLocalizationService(),
                "getCurrentMultiSubgroup",
                [],
                null
            );
        }

        function getCurrentMultiSubgroupName() {
            return callServiceMethod(
                "mainGroupLocalizationServices",
                getMainGroupLocalizationService(),
                "getCurrentMultiSubgroupName",
                [],
                "subgroup"
            );
        }

        function syncCurrentMultiStateToActiveSubgroup() {
            return callServiceMethod(
                "mainGroupLocalizationServices",
                getMainGroupLocalizationService(),
                "syncCurrentMultiStateToActiveSubgroup",
                [],
                undefined
            );
        }

        function loadCurrentMultiStateFromActiveSubgroup() {
            return callServiceMethod(
                "mainGroupLocalizationServices",
                getMainGroupLocalizationService(),
                "loadCurrentMultiStateFromActiveSubgroup",
                [],
                undefined
            );
        }

        return Object.freeze({
            updateClocks,
            getPersistenceSnapshot,
            parseAutoGeneratedIndexedName,
            localizeAutoGeneratedNamesForCurrentLanguage,
            getCurrentMultiSubgroup,
            getCurrentMultiSubgroupName,
            syncCurrentMultiStateToActiveSubgroup,
            loadCurrentMultiStateFromActiveSubgroup
        });
    }

    globalObj.GTVMainOrchestrationFlowServices = Object.freeze({
        createService
    });
})(typeof window !== "undefined" ? window : globalThis);
